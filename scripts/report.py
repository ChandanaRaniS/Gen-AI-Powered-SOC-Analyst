import os
from datetime import datetime

from reportlab.lib import colors
from reportlab.lib.enums import TA_CENTER
from reportlab.lib.styles import getSampleStyleSheet
from reportlab.lib.units import inch

from reportlab.platypus import (
    SimpleDocTemplate,
    Paragraph,
    Spacer,
    Table,
    TableStyle,
    Flowable
)

# ============================================================
# Confidence Progress Bar
# ============================================================

class ConfidenceBar(Flowable):

    def __init__(self, confidence):
        super().__init__()

        self.confidence = confidence
        self.width = 360
        self.height = 16

    def draw(self):

        # Background

        self.canv.setFillColor(colors.HexColor("#E6E6E6"))

        self.canv.roundRect(
            0,
            0,
            self.width,
            self.height,
            8,
            fill=1,
            stroke=0
        )

        # Filled Portion

        self.canv.setFillColor(colors.HexColor("#1428A0"))

        filled_width = (self.confidence / 100) * self.width

        self.canv.roundRect(
            0,
            0,
            filled_width,
            self.height,
            8,
            fill=1,
            stroke=0
        )

        # Percentage

        self.canv.setFillColor(colors.black)

        self.canv.setFont("Helvetica-Bold", 11)

        self.canv.drawString(
            self.width + 15,
            3,
            f"{self.confidence}%"
        )
        
# ============================================================
# PDF Function
# ============================================================

def generate_pdf(report, filename):

    # =====================================================
    # Create Reports Folder
    # =====================================================

    reports_dir = "reports"
    os.makedirs(reports_dir, exist_ok=True)

    # =====================================================
    # Generate Report ID and PDF Name
    # =====================================================

    report_id = "SOC-" + datetime.now().strftime("%Y%m%d-%H%M%S")

    filename = os.path.join(
        reports_dir,
        f"{report_id}.pdf"
    )

    doc = SimpleDocTemplate(
        filename,
        rightMargin=35,
        leftMargin=35,
        topMargin=35,
        bottomMargin=35
    )

    styles = getSampleStyleSheet()

    # -----------------------------
    # Styles
    # -----------------------------

    title_style = styles["Title"]
    title_style.alignment = TA_CENTER
    title_style.textColor = colors.white
    title_style.fontSize = 22

    heading_style = styles["Heading2"]
    heading_style.textColor = colors.darkblue

    normal_style = styles["BodyText"]
    normal_style.leading = 18
    normal_style.spaceAfter = 6

    story = []

    # =====================================================
    # Header
    # =====================================================

    title_table = Table(
        [["AI SOC INCIDENT REPORT"]],
        colWidths=[6.7 * inch]
    )

    title_table.setStyle(TableStyle([
        ("BACKGROUND", (0, 0), (-1, -1), colors.darkblue),
        ("TEXTCOLOR", (0, 0), (-1, -1), colors.white),
        ("ALIGN", (0, 0), (-1, -1), "CENTER"),
        ("FONTNAME", (0, 0), (-1, -1), "Helvetica-Bold"),
        ("FONTSIZE", (0, 0), (-1, -1), 22),
        ("TOPPADDING", (0, 0), (-1, -1), 14),
        ("BOTTOMPADDING", (0, 0), (-1, -1), 14),
    ]))

    story.append(title_table)
    story.append(Spacer(1, 18))

    # =====================================================
    # Report Information
    # =====================================================

    report_info = [
    ["Report ID", report_id],
    ["Generated On", datetime.now().strftime("%d-%b-%Y %I:%M %p")],
    ["Generated By", "AI SOC Analyst Assistant"],
]

    info_table = Table(
        report_info,
        colWidths=[2.0 * inch, 4.7 * inch]
    )

    info_table.setStyle(TableStyle([
        ("BACKGROUND", (0, 0), (0, -1), colors.lightgrey),
        ("GRID", (0, 0), (-1, -1), 0.5, colors.grey),
        ("FONTNAME", (0, 0), (0, -1), "Helvetica-Bold"),
        ("BOTTOMPADDING", (0, 0), (-1, -1), 8),
    ]))

    story.append(info_table)
    story.append(Spacer(1, 18))

    # =====================================================
    # Executive Summary
    # =====================================================

    story.append(
        Paragraph(
            "<font size='16' color='darkblue'><b>Executive Summary</b></font>",
            heading_style,
        )
    )

    story.append(Spacer(1, 10))


    # =====================================================
    # Report Content
    # =====================================================

        # =====================================================
    # Report Content
    # =====================================================

    for line in report.split("\n"):

        line = line.strip()

        if not line:
            story.append(Spacer(1, 6))
            continue

        # ---------------------------------------------
        # Section Headings
        # ---------------------------------------------

        if line.startswith("#"):

            heading = line.replace("#", "").strip()

            story.append(Spacer(1, 12))

            story.append(
                Paragraph(
                    f"<font size='15' color='darkblue'><b>{heading}</b></font>",
                    heading_style
                )
            )

            story.append(Spacer(1, 6))

        # ---------------------------------------------
        # Overall Confidence Score
        # ---------------------------------------------

        elif "Overall Confidence Score" in line:

            try:

                confidence = float(
                    line.split(":")[1]
                    .replace("%", "")
                    .strip()
                )

                story.append(
                    Paragraph(
                        f"<b>Overall Confidence Score: {confidence}%</b>",
                        normal_style
                    )
                )

                story.append(Spacer(1, 8))

                story.append(
                    ConfidenceBar(confidence)
                )

                story.append(Spacer(1, 15))

            except Exception:

                story.append(
                    Paragraph(line, normal_style)
                )

        # ---------------------------------------------
        # Normal Text
        # ---------------------------------------------

        else:

            story.append(
                Paragraph(
                    line,
                    normal_style
                )
            )
                    # =====================================================
    # Footer
    # =====================================================

    story.append(Spacer(1, 25))

    story.append(
        Paragraph(
            "<font color='grey'>"
            "<b>Generated by AI SOC Analyst Assistant</b><br/>"
            "Generative AI • RAG • MITRE ATT&CK • CVE • NIST • ChromaDB"
            "</font>",
            normal_style,
        )
    )

    # =====================================================
    # Build PDF
    # =====================================================

    doc.build(story)

    print(f"\nPDF saved successfully: {filename}")